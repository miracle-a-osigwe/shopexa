# Helper functions for Bedrock Bidirectional Event Stream
def _session_start_event() -> str:
    return json.dumps(
        {
            "event": {
                "sessionStart": {
                    "inferenceConfiguration": {
                        "maxTokens": 1024,
                        "topP": 0.9,
                        "temperature": 0.7,
                    }
                }
            }
        }
    )


def _prompt_start_event(prompt_name: str) -> str:
    return json.dumps(
        {
            "event": {
                "promptStart": {
                    "promptName": prompt_name,
                    "textOutputConfiguration": {"mediaType": "text/plain"},
                    "audioOutputConfiguration": {
                        "mediaType": "audio/lpcm",
                        "sampleRateHertz": OUTPUT_SAMPLE_RATE,
                        "sampleSizeBits": 16,
                        "channelCount": 1,
                        "voiceId": "matthew",
                        "encoding": "base64",
                        "audioType": "SPEECH",
                    },
                    "toolUseOutputConfiguration": {"mediaType": "application/json"},
                    "toolConfiguration": {"tools": NOVA_TOOLS},
                }
            }
        }
    )


def _system_prompt_events(prompt_name: str, content_name: str) -> List[str]:
    start = json.dumps(
        {
            "event": {
                "contentStart": {
                    "promptName": prompt_name,
                    "contentName": content_name,
                    "type": "TEXT",
                    "role": "SYSTEM",
                    "interactive": False,
                    "textInputConfiguration": {"mediaType": "text/plain"},
                }
            }
        }
    )
    text = json.dumps(
        {
            "event": {
                "textInput": {
                    "promptName": prompt_name,
                    "contentName": content_name,
                    "content": SYSTEM_PROMPT,
                }
            }
        }
    )
    end = json.dumps(
        {
            "event": {
                "contentEnd": {"promptName": prompt_name, "contentName": content_name}
            }
        }
    )
    return [start, text, end]


def _audio_content_start_event(prompt_name: str, content_name: str) -> str:
    return json.dumps(
        {
            "event": {
                "contentStart": {
                    "promptName": prompt_name,
                    "contentName": content_name,
                    "type": "AUDIO",
                    "interactive": True,
                    "role": "USER",
                    "audioInputConfiguration": {
                        "mediaType": "audio/lpcm",
                        "sampleRateHertz": INPUT_SAMPLE_RATE,
                        "sampleSizeBits": 16,
                        "channelCount": 1,
                        "audioType": "SPEECH",
                        "encoding": "base64",
                    },
                }
            }
        }
    )


def _audio_chunk_event(prompt_name: str, content_name: str, audio_b64: str) -> str:
    return json.dumps(
        {
            "event": {
                "audioInput": {
                    "promptName": prompt_name,
                    "contentName": content_name,
                    "content": audio_b64,
                }
            }
        }
    )


def _content_end_event(prompt_name: str, content_name: str) -> str:
    return json.dumps(
        {
            "event": {
                "contentEnd": {"promptName": prompt_name, "contentName": content_name}
            }
        }
    )


def _prompt_end_event(prompt_name: str) -> str:
    return json.dumps({"event": {"promptEnd": {"promptName": prompt_name}}})


def _session_end_event() -> str:
    return json.dumps({"event": {"sessionEnd": {}}})


def _tool_result_events(
    prompt_name: str, tool_use_id: str, content_name: str, result_str: str
) -> List[str]:
    start = json.dumps(
        {
            "event": {
                "contentStart": {
                    "promptName": prompt_name,
                    "contentName": content_name,
                    "interactive": False,
                    "type": "TOOL",
                    "role": "TOOL",
                    "toolResultInputConfiguration": {
                        "toolUseId": tool_use_id,
                        "type": "TEXT",
                        "textInputConfiguration": {"mediaType": "text/plain"},
                    },
                }
            }
        }
    )
    tool_result = json.dumps(
        {
            "event": {
                "toolResult": {
                    "promptName": prompt_name,
                    "contentName": content_name,
                    "content": result_str,
                }
            }
        }
    )
    end = json.dumps(
        {
            "event": {
                "contentEnd": {"promptName": prompt_name, "contentName": content_name}
            }
        }
    )
    return [start, tool_result, end]


# ── Bedrock Nova Sonic Bidirectional Session ──────────────────────────────────
async def _run_bedrock_sonic_session(browser_ws: WebSocket) -> bool:
    try:
        from aws_sdk_bedrock_runtime.client import (
            AsyncBedrockRuntimeClient,
            InvokeModelWithBidirectionalStreamOperationInput,
        )
        from aws_sdk_bedrock_runtime.models import (
            InvokeModelWithBidirectionalStreamInputChunk,
            BidirectionalInputPayloadPart,
        )
        from aws_sdk_bedrock_runtime.config import AsyncBedrockRuntimeConfig
        from smithy_aws_core.identity.environment import EnvironmentCredentialsResolver
        from smithy_aws_core.identity.static import StaticCredentialsResolver
        from smithy_aws_core.identity import AWSCredentialsIdentity
        from smithy_http.aio.crt import AWSCRTHTTPClient
    except ImportError as e:
        print(f"[NovaSonicBridge] Bedrock CRT SDK not installed: {e}")
        return False

    region = os.getenv("AWS_REGION", "us-east-1")

    try:
        key = os.getenv("AWS_ACCESS_KEY_ID", "")
        secret = os.getenv("AWS_SECRET_ACCESS_KEY", "")
        token = os.getenv("AWS_SESSION_TOKEN", None)
        if key and secret:
            identity = AWSCredentialsIdentity(
                access_key_id=key, secret_access_key=secret, session_token=token
            )
            resolver = StaticCredentialsResolver(identity=identity)
        else:
            resolver = EnvironmentCredentialsResolver()

        config = await AsyncBedrockRuntimeConfig.resolve(
            endpoint_uri=f"https://bedrock-runtime.{region}.amazonaws.com",
            region=region,
            transport=AWSCRTHTTPClient(),
            aws_credentials_identity_resolver=resolver,
        )
        client = AsyncBedrockRuntimeClient(config=config)
        stream_response = await client.invoke_model_with_bidirectional_stream(
            InvokeModelWithBidirectionalStreamOperationInput(model_id=MODEL_ID)
        )
    except Exception as e:
        print(
            f"[NovaSonicBridge] Bedrock Nova Sonic invoke unavailable ({MODEL_ID}): {e}"
        )
        return False

    prompt_name = str(uuid.uuid4())
    audio_content_name = str(uuid.uuid4())
    sys_content_name = str(uuid.uuid4())
    is_active = True
    send_lock = asyncio.Lock()
    script_cue_triggered = False

    async def send_event(event_json: str):
        if not is_active:
            return
        async with send_lock:
            chunk = InvokeModelWithBidirectionalStreamInputChunk(
                value=BidirectionalInputPayloadPart(bytes_=event_json.encode("utf-8"))
            )
            await stream_response.input_stream.send(chunk)

    try:
        await send_event(_session_start_event())
        await send_event(_prompt_start_event(prompt_name))
        for ev in _system_prompt_events(prompt_name, sys_content_name):
            await send_event(ev)
        await send_event(_audio_content_start_event(prompt_name, audio_content_name))
        output = await stream_response.await_output()
    except Exception as e:
        print(f"[NovaSonicBridge] Handshake failed: {e}")
        try:
            await stream_response.close()
        except Exception:
            pass
        return False

    await browser_ws.send_json(
        {
            "type": "session_ready",
            "sample_rate": OUTPUT_SAMPLE_RATE,
            "engine": "bedrock_sonic",
        }
    )
    telemetry.emit_thinking(
        "🎙️ Amazon Nova Sonic bidirectional stream established (24kHz Matthew)"
    )

    session_start_time = asyncio.get_event_loop().time()
    last_audio_sent_time = session_start_time
    audio_content_open = True

    async def receive_browser_audio():
        nonlocal is_active, last_audio_sent_time, prompt_name, audio_content_name, audio_content_open
        try:
            while is_active:
                raw = await browser_ws.receive_text()
                msg = json.loads(raw)
                mtype = msg.get("type")

                if mtype == "audio":
                    chunk_ev = _audio_chunk_event(
                        prompt_name, audio_content_name, msg["data"]
                    )
                    await send_event(chunk_ev)
                    last_audio_sent_time = asyncio.get_event_loop().time()

                elif mtype == "end_of_speech":
                    if audio_content_open:
                        await send_event(
                            _content_end_event(prompt_name, audio_content_name)
                        )
                        await send_event(_prompt_end_event(prompt_name))
                        audio_content_open = False

                elif mtype == "start_of_speech":
                    prompt_name = str(uuid.uuid4())
                    audio_content_name = str(uuid.uuid4())
                    await send_event(_prompt_start_event(prompt_name))
                    await send_event(
                        _audio_content_start_event(prompt_name, audio_content_name)
                    )
                    audio_content_open = True
                    last_audio_sent_time = asyncio.get_event_loop().time()

                elif mtype == "barge_in":
                    telemetry.emit_barge_in()

                elif mtype == "ambient_alert":
                    alert_text = (
                        msg.get("spoken_interrupted")
                        if msg.get("was_speaking")
                        else msg.get("spoken", "")
                    )
                    if alert_text:
                        alert_content_name = str(uuid.uuid4())
                        start_ev = json.dumps(
                            {
                                "event": {
                                    "contentStart": {
                                        "promptName": prompt_name,
                                        "contentName": alert_content_name,
                                        "interactive": True,
                                        "type": "TEXT",
                                        "role": "USER",
                                        "textInputConfiguration": {
                                            "mediaType": "text/plain"
                                        },
                                    }
                                }
                            }
                        )
                        instruction = f"A system notice arrived. Please announce warmly to the user: '{alert_text}'"
                        data_ev = json.dumps(
                            {
                                "event": {
                                    "textInput": {
                                        "promptName": prompt_name,
                                        "contentName": alert_content_name,
                                        "content": instruction,
                                    }
                                }
                            }
                        )
                        end_ev = json.dumps(
                            {
                                "event": {
                                    "contentEnd": {
                                        "promptName": prompt_name,
                                        "contentName": alert_content_name,
                                    }
                                }
                            }
                        )
                        await send_event(start_ev)
                        await send_event(data_ev)
                        await send_event(end_ev)

        except Exception:
            is_active = False

    async def output_worker():
        nonlocal is_active, prompt_name, script_cue_triggered
        curr_tool_name = None
        curr_tool_id = None
        curr_tool_args = ""

        try:
            while is_active:
                try:
                    res = await output[1].receive()
                except StopAsyncIteration:
                    break
                except Exception as e:
                    if is_active:
                        print(f"[NovaSonicBridge] Output stream notice: {e}")
                    break

                if not res or not res.value or not res.value.bytes_:
                    continue

                try:
                    payload = json.loads(res.value.bytes_.decode("utf-8"))
                except Exception:
                    continue

                ev = payload.get("event", {})

                # Audio chunk from Nova Sonic
                if "audioOutput" in ev:
                    audio_b64 = ev["audioOutput"].get("content", "")
                    if audio_b64:
                        await browser_ws.send_json(
                            {
                                "type": "audio",
                                "data": audio_b64,
                                "sample_rate": OUTPUT_SAMPLE_RATE,
                            }
                        )

                # Transcripts & Attention Evaluation
                elif "textOutput" in ev:
                    text_out = ev["textOutput"]
                    text_content = text_out.get("content", "")
                    role = text_out.get("role", "ASSISTANT")

                    # ── SQUELCH FILTER: Block rogue silence words ──
                    if role == "ASSISTANT":
                        squelch_words = [
                            "silent",
                            "silent.",
                            "silence",
                            "silence.",
                            "standing by",
                            "standing by.",
                            "[silent]",
                            "(silent)",
                        ]
                        if text_content.strip().lower() in squelch_words:
                            continue

                    if text_out.get("interrupted") is True:
                        telemetry.emit_barge_in()
                        await browser_ws.send_json({"type": "barge_in"})
                        continue

                    if not text_content or not text_content.strip():
                        continue

                    # ── Evaluate Attention on User Utterance ─────────────────
                    if role == "USER":
                        attn = AttentionGate.classify(text_content)
                        telemetry.emit_user_input(text_content)
                        print(attn)

                        # Broadcast user transcript to UI so dialogue bubble updates
                        await browser_ws.send_json(
                            {
                                "type": "transcript",
                                "text": text_content,
                                "role": "USER",
                                "attention": attn,
                            }
                        )

                        # 🎯 SCRIPT HOOK: "Meet Shopexa Ops" triggers Coffee Price Spike on cue!
                        clean_lower = text_content.lower()
                        if (
                            "meet shopexa" in clean_lower
                            or "meet shopexa ops" in clean_lower
                        ) and not script_cue_triggered:
                            script_cue_triggered = True
                            telemetry.emit_thinking(
                                "🎯 Presentation Cue Detected: 'Meet Shopexa Ops' -> Triggering Proactive Coffee Price Spike"
                            )
                            sc = ambient.trigger_scenario("supplier_price_spike")
                            if sc:
                                # Trigger card on frontend
                                await browser_ws.send_json(
                                    {
                                        "type": "price_spike_detected",
                                        "detail": sc.get("detail", ""),
                                    }
                                )
                            # Broadcast user speech to UI as STANDBY so bubble NEVER shows "Streaming response..."
                            await browser_ws.send_json(
                                {
                                    "type": "transcript",
                                    "text": text_content,
                                    "role": "USER",
                                    "attention": {
                                        "action": "STANDBY",
                                        "intent": "PRESENTER_NARRATION",
                                    },
                                }
                            )
                            telemetry.emit_presenter_aside(
                                text_content, "Pitch hook delivery — AI in Standby"
                            )

                        # # If presenter was explaining to judges, do not execute tools
                        # if attn.get("action") == "STANDBY":
                        #     await browser_ws.send_json(
                        #         {
                        #             "type": "transcript",
                        #             "text": text_content,
                        #             "role": "USER",
                        #             "attention": attn,
                        #         }
                        #     )
                        #     telemetry.emit_presenter_aside(
                        #         text_content,
                        #         "Presenter explaining to judges — AI on standby",
                        #     )
                        #     continue

                        # # Valid Direct Command -> Broadcast for execution
                        # await browser_ws.send_json(
                        #     {
                        #         "type": "transcript",
                        #         "text": text_content,
                        #         "role": "USER",
                        #         "attention": attn,
                        #     }
                        # )

                    else:
                        # ASSISTANT speech
                        telemetry.emit_agent_reply(text_content)
                        await browser_ws.send_json(
                            {
                                "type": "transcript",
                                "text": text_content,
                                "role": "ASSISTANT",
                            }
                        )

                # Tool use call from Sonic
                elif "toolUse" in ev:
                    tu = ev["toolUse"]
                    curr_tool_name = tu.get("toolName")
                    curr_tool_id = tu.get("toolUseId")
                    curr_tool_args = tu.get("content", "")

                # Tool execution delegation to Nova Pro / MCP
                elif (
                    "contentEnd" in ev
                    and ev.get("contentEnd", {}).get("type") == "TOOL"
                ):
                    if curr_tool_name and curr_tool_id:
                        tool_name = curr_tool_name
                        tool_id = curr_tool_id
                        parsed_args = {}
                        if curr_tool_args:
                            try:
                                parsed_args = json.loads(curr_tool_args)
                            except Exception:
                                parsed_args = {"raw": curr_tool_args}

                        telemetry.emit_dual_model_handoff(
                            from_model="Amazon Nova Sonic (Speech)",
                            to_model="Amazon Nova Pro (Reasoning & MCP)",
                            task=f"Executing '{tool_name}'",
                        )

                        import main as main_app
                        import modality_router as _mr

                        _router = _mr.router

                        user_intent = parsed_args.get("user_intent", "")
                        if tool_name == "agent_mcp":
                            mcp_result = await asyncio.to_thread(
                                _router._autonomous_mcp_execute,
                                user_intent,
                                list(main_app.conversation_history),
                                [],
                                True,
                                True,
                            )
                            text_result = mcp_result.get("text", "Task completed.")
                        elif tool_name == "resume_previous_flow":
                            text_result = shopexa_tools.resume_previous_flow(
                                parsed_args.get("order_id")
                            )
                        else:
                            text_result = f"Unknown tool {tool_name}"

                        result_str = json.dumps({"result": text_result})
                        tool_content_name = str(uuid.uuid4())
                        for tool_ev in _tool_result_events(
                            prompt_name, tool_id, tool_content_name, result_str
                        ):
                            await send_event(tool_ev)

                        # UI updates based on MCP tool outputs
                        if "ORDER_CREATED_SUCCESSFULLY" in text_result:
                            parts = text_result.split("\n")[0].split("|")
                            oid = parts[1] if len(parts) > 1 else "10"
                            amt = parts[2] if len(parts) > 2 else "37.00"
                            await browser_ws.send_json(
                                {
                                    "type": "order_created",
                                    "order_id": oid,
                                    "amount": amt,
                                    "detail": text_result,
                                }
                            )
                        elif "INVENTORY_RESULTS" in text_result:
                            await browser_ws.send_json(
                                {"type": "inventory_result", "detail": text_result}
                            )
                        elif "ORDER_AUTHORIZED_SUCCESSFULLY" in text_result:
                            await browser_ws.send_json(
                                {"type": "order_authorized", "detail": text_result}
                            )

                        curr_tool_name = None
                        curr_tool_id = None
                        curr_tool_args = ""

        except Exception as e:
            print(f"[NovaSonicBridge] Bedrock loop exception: {e}")
        finally:
            is_active = False

    recv_task = asyncio.create_task(receive_browser_audio())
    output_task = asyncio.create_task(output_worker())

    try:
        # Wait for either the browser to disconnect or the Bedrock stream to end
        await asyncio.wait(
            [recv_task, output_task], return_when=asyncio.FIRST_COMPLETED
        )
    except Exception as e:
        print(f"[NovaSonicBridge] Stream wait notice: {e}")
    finally:
        is_active = False

        # 1. Gracefully close the Bedrock CRT duplex stream FIRST so CRT stops delivering chunks
        try:
            await send_event(_session_end_event())
        except Exception:
            pass

        try:
            if hasattr(stream_response, "input_stream"):
                await stream_response.input_stream.close()
        except Exception:
            pass

        try:
            await asyncio.wait_for(stream_response.close(), timeout=1.0)
        except Exception:
            pass

        # 2. Cancel the background worker tasks only AFTER CRT is closed
        for t in [recv_task, output_task]:
            if not t.done():
                t.cancel()

        # Suppress any lingering CancelledErrors from the cancelled tasks
        await asyncio.gather(recv_task, output_task, return_exceptions=True)

    return True


